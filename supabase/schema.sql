create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null default 'Player',
  created_at timestamptz not null default now()
);
create table if not exists public.quiz_attempts (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  category text not null, topic text not null default 'All topics',
  difficulty text not null default 'All levels',
  total_questions integer not null check (total_questions > 0),
  correct_answers integer not null check (correct_answers >= 0 and correct_answers <= total_questions),
  duration_seconds integer not null default 0 check (duration_seconds >= 0),
  completed_at timestamptz not null default now()
);
alter table public.profiles enable row level security;
alter table public.quiz_attempts enable row level security;
create policy "Profiles readable by everyone for leaderboard" on public.profiles for select using (true);
create policy "Users insert own profile" on public.profiles for insert with check (auth.uid() = id);
create policy "Users update own profile" on public.profiles for update using (auth.uid() = id) with check (auth.uid() = id);
create policy "Users read own attempts" on public.quiz_attempts for select using (auth.uid() = user_id);
create policy "Users insert own attempts" on public.quiz_attempts for insert with check (auth.uid() = user_id);
create index if not exists quiz_attempts_user_completed_idx on public.quiz_attempts(user_id, completed_at desc);
create or replace view public.leaderboard as
select p.id as user_id, p.display_name, count(a.id)::integer as quizzes,
       coalesce(sum(a.correct_answers),0)::bigint as points,
       round(100.0 * coalesce(sum(a.correct_answers),0) / nullif(sum(a.total_questions),0), 1) as accuracy
from public.profiles p left join public.quiz_attempts a on a.user_id = p.id
group by p.id, p.display_name;
